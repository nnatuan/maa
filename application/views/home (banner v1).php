document.addEventListener("DOMContentLoaded", function () {
    // Chọn tất cả các nút có class bắt đầu bằng bt_bb_link_
    const toggleButtons = document.querySelectorAll('a[class*="bt_bb_link_"]');

    toggleButtons.forEach(button => {
        button.addEventListener("click", function (e) {
            e.preventDefault();

            // Lấy ID từ class của nút (ví dụ: từ bt_bb_link_45 lấy ra 45)
            const nid = this.className.match(/bt_bb_link_(\d+)/)[1];
            const content = document.getElementById("course_content_" + nid);
            const buttonText = this.querySelector(".bt_bb_button_text");
            const iconHolder = this.querySelector(".bt_bb_icon_holder");

            if (content) {
                // Toggle class expanded thay vì hide
                const isExpanded = content.classList.toggle("expanded");

                // Cập nhật Text và Icon theo trạng thái mở rộng
                if (isExpanded) {
                    buttonText.textContent = "Collapse";
                    iconHolder.innerHTML = "&#9650;"; // Mũi tên lên
                } else {
                    buttonText.textContent = "View more";
                    iconHolder.innerHTML = "&#9660;"; // Mũi tên xuống
                }
            }
        });
    });
});
</script>		

